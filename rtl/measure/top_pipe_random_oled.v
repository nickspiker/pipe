// =============================================================================
// top_pipe_random_oled.v — LFSR-driven random bits on the wire + geiger LED
// =============================================================================
// Variant of top_pipe_toggle_oled.v. Two functional changes vs the toggle:
//
//   * Wire driver: instead of a clean square wave (every slot has a transition),
//     an LFSR-driven decision per slot either flips `pipe_pad` or holds it.
//     ~50% transition density per slot → geometric distribution of inter-edge
//     intervals (mean 2 slots; P(1)=0.5, P(2)=0.25, P(3)=0.125, ...). Stress
//     test for the bridge's CDR: same slot rate as toggle, but the bridge has
//     to identify slot boundaries even with sparse transitions.
//
//   * Heartbeat LED: instead of a uniform divide-by-N blink, an LFSR-stepped
//     random pattern (geiger style), matching the bridge's geiger_task look.
//
// Everything else (OLED freq readout, ring osc placement, glyph rendering) is
// identical to top_pipe_toggle_oled.v. Pin map (constraints/pipe_random_oled.lpf)
// matches pipe_toggle_oled.lpf one-to-one.
//
// (Original top_pipe_oled.v doc kept for reference:)
// Renders four lines of variable-width Merriweather text. Three lines are static; one is live — a freq_counter measures the enclave's ring-oscillator-derived clock against the 25 MHz crystal over a 200 ms window, the result is binary-to-BCD converted, the resulting digit characters are written into the string register array, and the renderer is retriggered. Visible update rate: 5 Hz.
//
// Atlas inputs (generated by tools/oled-bake-atlas at build time):
//   glyph_dims.vh    — `define CELL_W, CELL_H, PAD_LEFT, MAX_ASCENT, etc.
//   glyph_atlas.mem  — NUM_CHARS × CELL_W × CELL_H bytes, row-major within each cell.
//   glyph_advance.mem — NUM_CHARS bytes of advance widths.
//
// Layout (4 lines, 16-px line height = exactly 64 px tall):
//   line 0 baseline @ row 11 — "PIPE"
//   line 1 baseline @ row 27 — "EFUSED: NO"
//   line 2 baseline @ row 43 — "CLK: ####### Hz" (digits live)
//   line 3 baseline @ row 59 — (reserved for drift, Phase 2 later)
// Each cell is drawn at (cursor_x - PAD_LEFT, baseline_y - MAX_ASCENT).
// =============================================================================

`timescale 1ns / 1ps
`include "glyph_dims.vh"

module top_pipe_random_oled #(
    parameter integer CLK_DIV     = 7,            // 25 MHz / 7 → ~3.5 MHz CE → ~28 kHz SCL
    parameter integer RING_STAGES = 5,            // ring-osc stages (production matches the DUT bench)
    parameter integer RING_DIV    = 2048          // mod-N divider on the ring → enclave_clk (2048 = 8× slower, slot ~23 µs ≈ 44 kHz: matches top_pipe_slotted_oled, keeps bridge host loop inside its ~7.5 µs/iter ceiling so FIFO never fills)
)(
    input  wire clk,                              // 25 MHz external crystal (P6)
    output wire oled_scl,
    output wire oled_sda,
    output wire pipe_pad,                         // straight square-wave to the bridge (E16)
    output reg  led
);

    localparam integer CELL_W      = `GLYPH_CELL_W;
    localparam integer CELL_H      = `GLYPH_CELL_H;
    localparam integer PAD_LEFT    = `GLYPH_PAD_LEFT;
    localparam integer MAX_ASCENT  = `GLYPH_MAX_ASCENT;
    localparam integer NUM_CHARS   = `GLYPH_NUM_CHARS;
    localparam [7:0]   FIRST_CHAR  = `GLYPH_FIRST_CHAR;

    localparam integer FB_W = 128;
    localparam integer FB_H = 64;

    localparam integer MAX_CHARS_PER_LINE = 24;
    localparam integer NUM_LINES = 4;
    localparam integer STR_LEN = NUM_LINES * MAX_CHARS_PER_LINE;

    // -------------------------------------------------------------------------
    // TRNG (29 ring oscillators) — same pattern as top_pin_id.
    // -------------------------------------------------------------------------
    wire [28:0] ro_out;
    genvar gi;
    generate
        for (gi = 0; gi < 29; gi = gi + 1) begin : ro_gen
            (* keep, syn_keep="true" *) wire fb_ro;
            (* keep *) LUT4 #(.INIT(16'h0100)) ro (
                .A(fb_ro), .B(1'b0), .C(1'b0), .D(1'b1), .Z(fb_ro)
            );
            assign ro_out[gi] = fb_ro;
        end
    endgenerate

    reg [28:0] ro_prev = 0;
    always @(posedge clk) ro_prev <= ro_out;
    wire [28:0] jitter = ro_out ^ ro_prev;

    wire [28:0] mixed;
    generate
        for (gi = 0; gi < 29; gi = gi + 1) begin : mix_gen
            assign mixed[gi] = jitter[gi] ^ jitter[(gi + 7) % 29] ^ jitter[(gi + 13) % 29];
        end
    endgenerate

    wire [7:0] trng_out = mixed[7:0] ^ mixed[15:8] ^ mixed[23:16] ^ {3'b0, mixed[28:24]};

    // -------------------------------------------------------------------------
    // Geiger-counter LED — canonical pattern from rtl/top_pin_id.v and
    // rtl/measure/top_dut_bench.v. Markov chain over the active-low LED state,
    // driven by the 29-ring TRNG output above. Sample rate ≈ 763 Hz
    // (25 MHz / 32768). When the LED is ON (led=0, active-low), small chance
    // to flip OFF; when OFF (led=1), larger chance to flip back ON. Asymmetry
    // gives the visual of mostly-OFF with brief ON flashes — the geiger look.
    // -------------------------------------------------------------------------
    reg [14:0] geiger_cnt = 0;
    always @(posedge clk) begin
        geiger_cnt <= geiger_cnt + 1;
        if (&geiger_cnt) begin
            if (led && trng_out < 8'd8)            // OFF→ON: ~3% per sample
                led <= 1'b0;
            else if (!led && trng_out < 8'd100)    // ON→OFF: ~39% per sample
                led <= 1'b1;
        end
    end

    // -------------------------------------------------------------------------
    // Ring oscillator → mod-N divider → enclave_clk. BEL-pinned to X4/Y20
    // SLICEs A-C so the osc frequency is consistent build-to-build (same approach
    // as top_pipe_toggle.v — without pinning, freq swings ~10% across seeds).
    // The generate loop is unrolled because BEL needs a static string per cell.
    // Locked at RING_STAGES=5 default; if changed, BEL pins also need updating.
    // -------------------------------------------------------------------------
    (* noglobal *) wire [RING_STAGES-1:0] ring_q;
    (* keep, BEL="X4/Y20/SLICEA.K0" *)
    LUT4 #(.INIT(16'h5555)) ring_inv (
        .A(ring_q[RING_STAGES-1]), .B(1'b0), .C(1'b0), .D(1'b0),
        .Z(ring_q[0])
    );
    (* keep, BEL="X4/Y20/SLICEA.K1" *)
    LUT4 #(.INIT(16'hAAAA)) ring_buf_1 (
        .A(ring_q[0]), .B(1'b0), .C(1'b0), .D(1'b0), .Z(ring_q[1])
    );
    (* keep, BEL="X4/Y20/SLICEB.K0" *)
    LUT4 #(.INIT(16'hAAAA)) ring_buf_2 (
        .A(ring_q[1]), .B(1'b0), .C(1'b0), .D(1'b0), .Z(ring_q[2])
    );
    (* keep, BEL="X4/Y20/SLICEB.K1" *)
    LUT4 #(.INIT(16'hAAAA)) ring_buf_3 (
        .A(ring_q[2]), .B(1'b0), .C(1'b0), .D(1'b0), .Z(ring_q[3])
    );
    (* keep, BEL="X4/Y20/SLICEC.K0" *)
    LUT4 #(.INIT(16'hAAAA)) ring_buf_4 (
        .A(ring_q[3]), .B(1'b0), .C(1'b0), .D(1'b0), .Z(ring_q[4])
    );

    wire ring_raw;
    (* keep *) DCCA dcca_ring_raw (.CLKI(ring_q[0]), .CE(1'b1), .CLKO(ring_raw));

    localparam integer DIV_HALF = (RING_DIV >> 1);
    localparam integer DIV_W    = ($clog2(DIV_HALF) > 0) ? $clog2(DIV_HALF) : 1;
    reg [DIV_W-1:0] ring_div_cnt = 0;
    reg             ring_div_out = 0;
    always @(posedge ring_raw) begin
        if (ring_div_cnt == (DIV_HALF - 1)) begin
            ring_div_cnt <= 0;
            ring_div_out <= ~ring_div_out;
        end else begin
            ring_div_cnt <= ring_div_cnt + 1'b1;
        end
    end

    wire enclave_clk;
    (* keep *) DCCA dcca_enclave_clk (.CLKI(ring_div_out), .CE(1'b1), .CLKO(enclave_clk));

    // -------------------------------------------------------------------------
    // LFSR-driven wire. `slot_counter` runs the same /4 cadence as the toggle
    // bitstream (each slot = 4 enclave_clk cycles, slot rate ≈ 348 kHz). At
    // each slot boundary we draw a bit from the wire-side LFSR: bit=1 flips
    // `pipe_pad`, bit=0 holds. ~50% of slots have a transition. Same wire
    // frequency as the toggle case on average, but with the geometric
    // inter-edge distribution that real protocol data would produce.
    //
    // toggle_counter[2:0] is kept (driven below the LFSR) only to align the
    // OLED frequency counter, which clocks off enclave_clk — its readout is
    // still meaningful even with random transitions, because the counter
    // measures enclave_clk's rate, not the wire's transition rate.
    // -------------------------------------------------------------------------
    reg [15:0] toggle_counter = 0;
    always @(posedge enclave_clk) toggle_counter <= toggle_counter + 1'b1;

    // Galois LFSR for slot-level random bit draws. Seed must be nonzero; chosen
    // arbitrarily (different from the LED LFSR seed so they don't correlate).
    reg [31:0] wire_lfsr = 32'hDEADBEEF;
    reg        wire_out  = 1'b0;
    reg [1:0]  slot_phase = 2'd0;
    always @(posedge enclave_clk) begin
        slot_phase <= slot_phase + 1'b1;
        if (slot_phase == 2'd3) begin
            // Slot boundary — step LFSR and maybe flip the wire.
            wire_lfsr <= {wire_lfsr[30:0],
                          wire_lfsr[31] ^ wire_lfsr[21] ^ wire_lfsr[1] ^ wire_lfsr[0]};
            if (wire_lfsr[0]) wire_out <= ~wire_out;
        end
    end
    assign pipe_pad = wire_out;

    // -------------------------------------------------------------------------
    // Frequency counter (genlocked). The OLED pump emits `frame_pulse` once per frame as it wraps from page 7 back to page 0. We accumulate enclave_clk edges across one frame, then latch the count × MAGIC into `freq_hz` on the next frame_pulse and reset. One measurement per displayed frame — no aliasing, no drift between counter and display.
    //
    // Frame_pulse is generated below from the pump FSM; freq counter is inlined here so it can use frame_pulse directly without crossing module boundaries.
    // -------------------------------------------------------------------------
    reg         frame_pulse = 1'b0;  // 1-cycle pulse on every page-7 → page-0 wrap; driven in the OLED pump section below
    reg  [31:0] freq_hz     = 32'd0;
    reg         freq_valid  = 1'b0;

    // Cross-domain edge capture: meas_clk -> ref_clk via toggle FF + 2-FF sync.
    reg meas_toggle = 1'b0;
    always @(posedge enclave_clk) meas_toggle <= ~meas_toggle;
    reg [2:0] toggle_sync = 3'b0;
    always @(posedge clk) toggle_sync <= {toggle_sync[1:0], meas_toggle};
    wire meas_edge = toggle_sync[2] ^ toggle_sync[1];

    // Accumulator. Latches and resets on frame_pulse. MAGIC = 100 → assumes a ~10 ms frame; the displayed value scales linearly with the actual frame time, so a 1% jitter in the OLED FSM gives a 1% jitter in displayed Hz.
    localparam integer FREQ_MAGIC = 100;
    reg [23:0] edge_cnt = 24'd0;
    always @(posedge clk) begin
        freq_valid <= 1'b0;
        if (frame_pulse) begin
            freq_hz    <= edge_cnt * FREQ_MAGIC;
            edge_cnt   <= meas_edge ? 24'd1 : 24'd0;
            freq_valid <= 1'b1;
        end else if (meas_edge) begin
            edge_cnt <= edge_cnt + 24'd1;
        end
    end

    // -------------------------------------------------------------------------
    // Binary → BCD. Takes 24 cycles after `start`; result valid one cycle after `done` pulses.
    // -------------------------------------------------------------------------
    localparam integer BCD_DIGITS = 8;
    localparam integer BIN_W      = 24;
    wire [BCD_DIGITS*4-1:0] bcd;
    wire                    bcd_done;
    bin_to_bcd #(
        .BIN_W      (BIN_W),
        .BCD_DIGITS (BCD_DIGITS)
    ) b2b (
        .clk     (clk),
        .reset_n (1'b1),
        .start   (freq_valid),
        .bin     (freq_hz[BIN_W-1:0]),
        .bcd     (bcd),
        .done    (bcd_done)
    );

    // -------------------------------------------------------------------------
    // Framebuffer (8192 bytes). Single-port: renderer writes during boot, OLED pump reads after. Renderer drives we; once render_done is high, pump takes over reads.
    // -------------------------------------------------------------------------
    reg [7:0] fb [0:FB_W * FB_H - 1];
    // initialise to 0 so partial renders look right
    integer init_i;
    initial for (init_i = 0; init_i < FB_W * FB_H; init_i = init_i + 1) fb[init_i] = 8'h00;

    reg         fb_we = 0;
    reg [12:0]  fb_waddr = 0;
    reg [7:0]   fb_wdata = 0;
    reg [12:0]  fb_raddr = 0;
    reg [7:0]   fb_rdata = 0;

    always @(posedge clk) begin
        if (fb_we) fb[fb_waddr] <= fb_wdata;
        fb_rdata <= fb[fb_raddr];
    end

    // -------------------------------------------------------------------------
    // Glyph atlas + per-glyph advance ROMs (loaded from .mem files).
    // -------------------------------------------------------------------------
    localparam integer CELL_SIZE = CELL_W * CELL_H;
    localparam integer ATLAS_SIZE = NUM_CHARS * CELL_SIZE;

    reg [7:0] atlas [0:ATLAS_SIZE - 1];
    initial $readmemh("glyph_atlas.mem", atlas);

    reg [7:0] advance_w [0:NUM_CHARS - 1];
    initial $readmemh("glyph_advance.mem", advance_w);

    // -------------------------------------------------------------------------
    // String register array. Three lines static; line 2 has a fixed "CLK: " prefix and " Hz" suffix with 9 dynamic positions in between — 7 digits and 2 thousands-separator commas — written by the BCD update FSM whenever a new freq measurement completes. Leading zeros (and their immediately-preceding comma) collapse to spaces so e.g. 600 kHz displays as "  600,000" instead of "0,600,000".
    //
    // Line 2 layout: "CLK: " D,DDD,DDD " Hz"   (5 + 9 + 3 = 17 chars)
    //   offset 0..4 : "CLK: "                         (static)
    //   offset 5..13: D,DDD,DDD                       (dynamic — 9 chars)
    //   offset 14   : " "                             (static)
    //   offset 15..16: "Hz"                           (static)
    // -------------------------------------------------------------------------
    reg [7:0] strings [0:STR_LEN - 1];
    integer si;

    localparam integer LINE2_BASE       = 2 * MAX_CHARS_PER_LINE;
    localparam integer LINE2_DIGIT_BASE = LINE2_BASE + 5;   // strings[53..61]
    localparam integer LINE2_DYN_LEN    = 9;                // 7 digits + 2 commas

    initial begin
        for (si = 0; si < STR_LEN; si = si + 1) strings[si] = 8'h00;
        // line 0
        strings[ 0] = "P"; strings[ 1] = "I"; strings[ 2] = "P"; strings[ 3] = "E";
        // line 1
        strings[24] = "E"; strings[25] = "F"; strings[26] = "U"; strings[27] = "S";
        strings[28] = "E"; strings[29] = "D"; strings[30] = ":"; strings[31] = " ";
        strings[32] = "N"; strings[33] = "O";
        // line 2: "CLK: 0,000,000 Hz" (digits and commas get overwritten at runtime)
        strings[LINE2_BASE + 0] = "C";
        strings[LINE2_BASE + 1] = "L";
        strings[LINE2_BASE + 2] = "K";
        strings[LINE2_BASE + 3] = ":";
        strings[LINE2_BASE + 4] = " ";
        strings[LINE2_BASE + 5] = "0";
        strings[LINE2_BASE + 6] = ",";
        strings[LINE2_BASE + 7] = "0";
        strings[LINE2_BASE + 8] = "0";
        strings[LINE2_BASE + 9] = "0";
        strings[LINE2_BASE +10] = ",";
        strings[LINE2_BASE +11] = "0";
        strings[LINE2_BASE +12] = "0";
        strings[LINE2_BASE +13] = "0";
        strings[LINE2_BASE +14] = " ";
        strings[LINE2_BASE +15] = "H";
        strings[LINE2_BASE +16] = "z";
        // line 3 (reserved for drift display, blank for now)
    end

    // Runtime digit-and-comma write FSM. On bcd_done, walks the 9 dynamic positions, writing either an ASCII digit, a comma, or a space (for leading-zero collapse) at each step. Re-renders when done.
    // Position kinds within line 2 dynamic region (idx is 1-based for FSM tracking):
    //   1: digit (millions, BCD[27:24])
    //   2: comma
    //   3..5: digits (BCD[23:20], BCD[19:16], BCD[15:12])
    //   6: comma
    //   7..9: digits (BCD[11:8], BCD[7:4], BCD[3:0])
    reg [3:0] digit_write_idx = 4'd0;
    reg       seen_nonzero    = 1'b0;
    reg       re_render_req   = 1'b0;

    reg [3:0] sel_digit;
    reg       sel_is_comma;
    reg       sel_is_digit;
    reg       sel_is_last;
    always @* begin
        sel_is_comma = 1'b0;
        sel_is_digit = 1'b0;
        sel_is_last  = 1'b0;
        sel_digit    = 4'd0;
        case (digit_write_idx)
            4'd1: begin sel_is_digit = 1'b1; sel_digit = bcd[27:24]; end
            4'd2: sel_is_comma = 1'b1;
            4'd3: begin sel_is_digit = 1'b1; sel_digit = bcd[23:20]; end
            4'd4: begin sel_is_digit = 1'b1; sel_digit = bcd[19:16]; end
            4'd5: begin sel_is_digit = 1'b1; sel_digit = bcd[15:12]; end
            4'd6: sel_is_comma = 1'b1;
            4'd7: begin sel_is_digit = 1'b1; sel_digit = bcd[11:8]; end
            4'd8: begin sel_is_digit = 1'b1; sel_digit = bcd[7:4]; end
            4'd9: begin sel_is_digit = 1'b1; sel_digit = bcd[3:0]; sel_is_last = 1'b1; end
            default: ;
        endcase
    end

    // Computed character for this position.
    wire show_digit = sel_is_digit && (seen_nonzero || sel_digit != 4'd0 || sel_is_last);
    wire [7:0] sel_char = sel_is_comma ? (seen_nonzero ? 8'h2C : 8'h20)  // ',' or ' '
                       : show_digit   ? (8'h30 + {4'b0, sel_digit})    // '0'..'9'
                                       : 8'h20;                          // ' '

    always @(posedge clk) begin
        re_render_req <= 1'b0;
        if (bcd_done) begin
            digit_write_idx <= 4'd1;
            seen_nonzero    <= 1'b0;
        end else if (digit_write_idx != 4'd0) begin
            strings[LINE2_DIGIT_BASE + (digit_write_idx - 1)] <= sel_char;
            if (show_digit) seen_nonzero <= 1'b1;
            if (digit_write_idx == LINE2_DYN_LEN[3:0]) begin
                digit_write_idx <= 4'd0;
                re_render_req   <= 1'b1;
            end else begin
                digit_write_idx <= digit_write_idx + 4'd1;
            end
        end
    end

    // Per-line baseline Y in framebuffer rows.
    function [6:0] line_baseline(input [1:0] ln);
        case (ln)
            2'd0: line_baseline = 7'd11;
            2'd1: line_baseline = 7'd27;
            2'd2: line_baseline = 7'd43;
            2'd3: line_baseline = 7'd59;
        endcase
    endfunction

    // -------------------------------------------------------------------------
    // Renderer FSM. Re-runs on re_render_req (after a BCD update).
    // -------------------------------------------------------------------------
    localparam [3:0]
        R_BOOT     = 4'd0,  // wait a few cycles for $readmemh to settle
        R_CLEAR    = 4'd1,  // walk fb writing 0 to every cell (between repaints)
        R_LOAD     = 4'd2,  // fetch next char from strings[]
        R_LATCH    = 4'd3,  // wait one cycle so atlas/advance reads settle
        R_PX_READ  = 4'd4,  // read atlas pixel
        R_PX_WRITE = 4'd5,  // write framebuffer with max-blend
        R_ADV      = 4'd6,  // advance cursor, next char
        R_NEXT_LN  = 4'd7,
        R_DONE     = 4'd8;  // idle until re_render_req fires

    reg [3:0]  rstate     = R_BOOT;
    reg [4:0]  boot_cnt   = 0;
    reg [12:0] clear_addr = 0;
    reg [12:0] clear_end  = FB_W * FB_H - 1;
    reg        partial_mode = 1'b0;  // 0 = full repaint (boot), 1 = line-2 only (re-render)

    // Line 2 occupies framebuffer rows 32–47 (baseline @ 43, ascent 11, descent 4 → cell rows 32..47 inclusive).
    localparam integer LINE2_FB_START = 32 * FB_W;          // = 4096
    localparam integer LINE2_FB_END   = 48 * FB_W - 1;       // = 6143

    reg [1:0]  line_idx     = 0;
    reg [4:0]  char_in_line = 0;
    reg [6:0]  cursor_x     = 0;
    reg [7:0]  char_ascii   = 0;
    reg [6:0]  glyph_idx    = 0;   // ascii - FIRST_CHAR
    reg [3:0]  px_i = 0;            // 0..CELL_W-1
    reg [3:0]  px_j = 0;            // 0..CELL_H-1

    wire signed [8:0] dst_x = $signed({2'b00, cursor_x}) - $signed({2'b00, PAD_LEFT[6:0]}) + $signed({5'b0, px_i});
    wire signed [8:0] dst_y = $signed({2'b00, line_baseline(line_idx)}) - $signed({2'b00, MAX_ASCENT[6:0]}) + $signed({5'b0, px_j});

    wire dst_in_range = (dst_x >= 0) && (dst_x < FB_W) && (dst_y >= 0) && (dst_y < FB_H);

    wire [14:0] atlas_addr = {glyph_idx, px_j[3:0], px_i[3:0]};
    reg  [7:0]  atlas_pix = 0;
    always @(posedge clk) atlas_pix <= atlas[atlas_addr];

    wire render_done = (rstate == R_DONE);

    always @(posedge clk) begin
        fb_we <= 1'b0;

        case (rstate)
            R_BOOT: begin
                boot_cnt <= boot_cnt + 1;
                if (&boot_cnt) begin
                    partial_mode <= 1'b0;
                    clear_addr   <= 13'd0;
                    clear_end    <= FB_W * FB_H - 1;
                    rstate       <= R_CLEAR;
                end
            end

            R_CLEAR: begin
                fb_we    <= 1'b1;
                fb_waddr <= clear_addr;
                fb_wdata <= 8'h00;
                if (clear_addr == clear_end) begin
                    line_idx     <= partial_mode ? 2'd2 : 2'd0;
                    char_in_line <= 0;
                    cursor_x     <= 0;
                    rstate       <= R_LOAD;
                end else begin
                    clear_addr <= clear_addr + 1;
                end
            end

            R_LOAD: begin
                char_ascii <= strings[line_idx * MAX_CHARS_PER_LINE + char_in_line];
                rstate     <= R_LATCH;
            end

            R_LATCH: begin
                if (char_ascii == 8'h00) begin
                    rstate <= R_NEXT_LN;
                end else begin
                    glyph_idx <= char_ascii - FIRST_CHAR;
                    px_i      <= 0;
                    px_j      <= 0;
                    rstate    <= R_PX_READ;
                end
            end

            R_PX_READ: begin
                // atlas_pix updates one cycle after atlas_addr is set, so we wait through this state once per pixel for the read to settle.
                rstate <= R_PX_WRITE;
            end

            R_PX_WRITE: begin
                if (atlas_pix != 0 && dst_in_range) begin
                    fb_waddr <= dst_y[6:0] * FB_W + dst_x[7:0];
                    fb_wdata <= atlas_pix;
                    fb_we    <= 1'b1;
                end
                rstate <= R_ADV;
            end

            R_ADV: begin
                if (px_i == CELL_W - 1) begin
                    px_i <= 0;
                    if (px_j == CELL_H - 1) begin
                        // finished this glyph
                        cursor_x     <= cursor_x + advance_w[glyph_idx];
                        char_in_line <= char_in_line + 1;
                        if (char_in_line == MAX_CHARS_PER_LINE - 1) begin
                            rstate <= R_NEXT_LN;
                        end else begin
                            rstate <= R_LOAD;
                        end
                        px_j <= 0;
                    end else begin
                        px_j   <= px_j + 1;
                        rstate <= R_PX_READ;
                    end
                end else begin
                    px_i   <= px_i + 1;
                    rstate <= R_PX_READ;
                end
            end

            R_NEXT_LN: begin
                if (line_idx == NUM_LINES - 1 || (partial_mode && line_idx == 2'd2)) begin
                    rstate <= R_DONE;
                end else begin
                    line_idx     <= line_idx + 1;
                    char_in_line <= 0;
                    cursor_x     <= 0;
                    rstate       <= R_LOAD;
                end
            end

            R_DONE: begin
                // Wait for the BCD update FSM to ask for a re-paint. Re-renders are partial-mode: only line 2's framebuffer region gets cleared and only line 2 gets re-rendered, so the OLED pump never sees a half-cleared static line on the wire.
                if (re_render_req) begin
                    partial_mode <= 1'b1;
                    clear_addr   <= LINE2_FB_START[12:0];
                    clear_end    <= LINE2_FB_END[12:0];
                    rstate       <= R_CLEAR;
                end
            end
        endcase
    end

    // -------------------------------------------------------------------------
    // CE divider for the OLED pump.
    // -------------------------------------------------------------------------
    reg [$clog2(CLK_DIV)-1:0] cnt = 0;
    wire at_top = (cnt == CLK_DIV - 1);
    always @(posedge clk) cnt <= at_top ? 0 : cnt + 1;
    reg ce = 0;
    always @(posedge clk) ce <= at_top;

    // -------------------------------------------------------------------------
    // I2C driver.
    // -------------------------------------------------------------------------
    reg  [7:0] i2c_data;
    reg        i2c_start;
    reg        i2c_send_stop;
    wire       i2c_busy;

    ssd1306_i2c #(.CLK_DIV(CLK_DIV)) i2c (
        .clk(clk), .rst(1'b0),
        .data(i2c_data),
        .start(i2c_start),
        .send_start(1'b0),
        .send_stop(i2c_send_stop),
        .busy(i2c_busy),
        .scl(oled_scl), .sda(oled_sda)
    );

    // -------------------------------------------------------------------------
    // SSD1306 init sequence.
    // -------------------------------------------------------------------------
    localparam I2C_ADDR    = 8'h78;
    localparam CMD_PREFIX  = 8'h00;
    localparam DATA_PREFIX = 8'h40;
    localparam INIT_LEN    = 25;

    reg [7:0] init_cmds [0:INIT_LEN-1];
    initial begin
        init_cmds[ 0] = 8'hAE; init_cmds[ 1] = 8'hD5; init_cmds[ 2] = 8'h80;
        init_cmds[ 3] = 8'hA8; init_cmds[ 4] = 8'h3F; init_cmds[ 5] = 8'hD3;
        init_cmds[ 6] = 8'h00; init_cmds[ 7] = 8'h40; init_cmds[ 8] = 8'h8D;
        init_cmds[ 9] = 8'h14; init_cmds[10] = 8'hAD; init_cmds[11] = 8'h8B;
        init_cmds[12] = 8'hA1; init_cmds[13] = 8'hC8; init_cmds[14] = 8'hDA;
        init_cmds[15] = 8'h12; init_cmds[16] = 8'h81; init_cmds[17] = 8'hCF;
        init_cmds[18] = 8'hD9; init_cmds[19] = 8'hF1; init_cmds[20] = 8'hDB;
        init_cmds[21] = 8'h40; init_cmds[22] = 8'hA4; init_cmds[23] = 8'hA6;
        init_cmds[24] = 8'hAF;
    end

    // -------------------------------------------------------------------------
    // OLED pump FSM (unchanged from Phase 2A apart from using fb_raddr/fb_rdata).
    // -------------------------------------------------------------------------
    localparam [2:0]
        ST_RESET   = 3'd0, ST_SEND   = 3'd1, ST_WAIT  = 3'd2,
        ST_NEXT    = 3'd3, ST_BUSFREE = 3'd4, ST_GATHER = 3'd5;

    localparam [1:0]
        PH_INIT      = 2'd0, PH_PAGE_CMD = 2'd1, PH_PAGE_DATA = 2'd2;

    reg [2:0]  state       = ST_RESET;
    reg [1:0]  phase       = PH_INIT;
    reg [19:0] reset_cnt   = 0;
    reg [9:0]  busfree_cnt = 0;
    reg [4:0]  cmd_idx     = 0;
    reg [2:0]  page        = 0;
    reg [6:0]  col         = 0;
    reg [7:0]  px_byte     = 0;
    reg [3:0]  gather_cnt  = 0;

    // Frame boundary detector. We start in page 0 (page_was_zero = 1) so the very first transition that fires the pulse is page 7 → 0. Edge detected once per OLED frame wrap.
    reg page_was_zero = 1'b1;
    always @(posedge clk) begin
        frame_pulse <= 1'b0;
        if (ce) begin
            if ((page == 3'd0) && !page_was_zero) frame_pulse <= 1'b1;
            page_was_zero <= (page == 3'd0);
        end
    end

    always @(posedge clk) if (ce) begin
        fb_raddr  <= {page, gather_cnt[2:0], col};
        i2c_start <= 0;

        case (state)
            ST_RESET: begin
                reset_cnt <= reset_cnt + 1;
                // wait until renderer is finished AND reset counter elapsed
                if (&reset_cnt && render_done) begin
                    phase   <= PH_INIT;
                    cmd_idx <= 0;
                    page    <= 0;
                    col     <= 0;
                    state   <= ST_SEND;
                end
            end

            ST_SEND: begin
                if (!i2c_busy) begin
                    case (phase)
                        PH_INIT: begin
                            if (cmd_idx == 0)         begin i2c_data <= I2C_ADDR;             i2c_send_stop <= 0; end
                            else if (cmd_idx == 1)    begin i2c_data <= CMD_PREFIX;           i2c_send_stop <= 0; end
                            else                      begin i2c_data <= init_cmds[cmd_idx-2]; i2c_send_stop <= (cmd_idx == INIT_LEN + 1); end
                        end
                        PH_PAGE_CMD: begin
                            case (cmd_idx[2:0])
                                3'd0: begin i2c_data <= I2C_ADDR;             i2c_send_stop <= 0; end
                                3'd1: begin i2c_data <= CMD_PREFIX;           i2c_send_stop <= 0; end
                                3'd2: begin i2c_data <= 8'hB0 | {5'd0, page}; i2c_send_stop <= 0; end
                                3'd3: begin i2c_data <= 8'h02;                i2c_send_stop <= 0; end
                                3'd4: begin i2c_data <= 8'h10;                i2c_send_stop <= 1; end
                                default: ;
                            endcase
                        end
                        PH_PAGE_DATA: begin
                            if (cmd_idx == 0)         begin i2c_data <= I2C_ADDR;    i2c_send_stop <= 0; end
                            else if (cmd_idx == 1)    begin i2c_data <= DATA_PREFIX; i2c_send_stop <= 0; end
                            else                      begin i2c_data <= px_byte;     i2c_send_stop <= (col == 7'd127); end
                        end
                    endcase
                    i2c_start <= 1;
                    state     <= ST_WAIT;
                end
            end

            ST_WAIT: begin
                if (i2c_busy) state <= ST_NEXT;
            end

            ST_NEXT: begin
                if (!i2c_busy) begin
                    case (phase)
                        PH_INIT: begin
                            if (cmd_idx == INIT_LEN + 1) begin
                                phase   <= PH_PAGE_CMD;
                                cmd_idx <= 0;
                                page    <= 0;
                                state   <= ST_BUSFREE;
                            end else begin
                                cmd_idx <= cmd_idx + 1;
                                state   <= ST_SEND;
                            end
                        end
                        PH_PAGE_CMD: begin
                            if (cmd_idx == 4) begin
                                phase      <= PH_PAGE_DATA;
                                cmd_idx    <= 0;
                                col        <= 0;
                                gather_cnt <= 0;
                                state      <= ST_BUSFREE;
                            end else begin
                                cmd_idx <= cmd_idx + 1;
                                state   <= ST_SEND;
                            end
                        end
                        PH_PAGE_DATA: begin
                            if (cmd_idx < 2) begin
                                cmd_idx <= cmd_idx + 1;
                                if (cmd_idx == 1) begin
                                    gather_cnt <= 0;
                                    state      <= ST_GATHER;
                                end else begin
                                    state <= ST_SEND;
                                end
                            end else if (col == 7'd127) begin
                                phase   <= PH_PAGE_CMD;
                                cmd_idx <= 0;
                                page    <= (page == 3'd7) ? 3'd0 : page + 1;
                                state   <= ST_BUSFREE;
                            end else begin
                                col        <= col + 1;
                                gather_cnt <= 0;
                                state      <= ST_GATHER;
                            end
                        end
                    endcase
                end
            end

            ST_BUSFREE: begin
                busfree_cnt <= busfree_cnt + 1;
                if (&busfree_cnt) begin
                    busfree_cnt <= 0;
                    state       <= ST_SEND;
                end
            end

            ST_GATHER: begin
                gather_cnt <= gather_cnt + 1;
                if (gather_cnt >= 4'd1) begin
                    px_byte <= {(fb_rdata >= trng_out), px_byte[7:1]};
                end
                if (gather_cnt == 4'd8) begin
                    gather_cnt <= 0;
                    state      <= ST_SEND;
                end
            end
        endcase
    end

endmodule
