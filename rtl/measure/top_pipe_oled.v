// =============================================================================
// top_pipe_oled.v — OLED bring-up for PIPE (Phase 2C: runtime glyph atlas)
// =============================================================================
// Carries a 95-char glyph atlas (printable ASCII, 16×16-byte cells), per-glyph advance widths, and a hardcoded string ROM. At reset a renderer FSM walks the string ROM and blits glyphs into the framebuffer; once it's done the OLED pump streams the framebuffer to the SSD1306 forever. Adding/replacing strings is a one-line edit + rebuild.
//
// Atlas inputs (generated by tools/oled-bake-atlas at build time):
//   glyph_dims.vh    — `define CELL_W, CELL_H, PAD_LEFT, MAX_ASCENT, etc.
//   glyph_atlas.mem  — NUM_CHARS × CELL_W × CELL_H bytes, row-major within each cell.
//   glyph_advance.mem — NUM_CHARS bytes of advance widths.
//
// Layout (4 lines, 16-px line height = exactly 64 px tall):
//   line 0 baseline @ row 11
//   line 1 baseline @ row 27
//   line 2 baseline @ row 43
//   line 3 baseline @ row 59
// Each cell is drawn at (cursor_x - PAD_LEFT, baseline_y - MAX_ASCENT).
// =============================================================================

`timescale 1ns / 1ps
`include "glyph_dims.vh"

module top_pipe_oled #(
    parameter integer CLK_DIV = 7   // 25 MHz / 7 → ~3.5 MHz CE → ~28 kHz SCL
)(
    input  wire clk,                // 25 MHz external crystal (P6)
    output wire oled_scl,
    output wire oled_sda,
    output reg  led
);

    localparam integer CELL_W      = `GLYPH_CELL_W;
    localparam integer CELL_H      = `GLYPH_CELL_H;
    localparam integer PAD_LEFT    = `GLYPH_PAD_LEFT;
    localparam integer MAX_ASCENT  = `GLYPH_MAX_ASCENT;
    localparam integer NUM_CHARS   = `GLYPH_NUM_CHARS;
    localparam [7:0]   FIRST_CHAR  = `GLYPH_FIRST_CHAR;

    localparam integer FB_W = 128;
    localparam integer FB_H = 64;

    localparam integer MAX_CHARS_PER_LINE = 24;
    localparam integer NUM_LINES = 4;
    localparam integer STR_LEN = NUM_LINES * MAX_CHARS_PER_LINE;

    // -------------------------------------------------------------------------
    // TRNG (29 ring oscillators) — same pattern as top_pin_id.
    // -------------------------------------------------------------------------
    wire [28:0] ro_out;
    genvar gi;
    generate
        for (gi = 0; gi < 29; gi = gi + 1) begin : ro_gen
            (* keep, syn_keep="true" *) wire fb_ro;
            (* keep *) LUT4 #(.INIT(16'h0100)) ro (
                .A(fb_ro), .B(1'b0), .C(1'b0), .D(1'b1), .Z(fb_ro)
            );
            assign ro_out[gi] = fb_ro;
        end
    endgenerate

    reg [28:0] ro_prev = 0;
    always @(posedge clk) ro_prev <= ro_out;
    wire [28:0] jitter = ro_out ^ ro_prev;

    wire [28:0] mixed;
    generate
        for (gi = 0; gi < 29; gi = gi + 1) begin : mix_gen
            assign mixed[gi] = jitter[gi] ^ jitter[(gi + 7) % 29] ^ jitter[(gi + 13) % 29];
        end
    endgenerate

    wire [7:0] trng_out = mixed[7:0] ^ mixed[15:8] ^ mixed[23:16] ^ {3'b0, mixed[28:24]};

    // -------------------------------------------------------------------------
    // Heartbeat LED.
    // -------------------------------------------------------------------------
    reg [22:0] hb_cnt = 0;
    always @(posedge clk) begin
        hb_cnt <= hb_cnt + 1;
        if (&hb_cnt) led <= ~led;
    end

    // -------------------------------------------------------------------------
    // Framebuffer (8192 bytes). Single-port: renderer writes during boot, OLED pump reads after. Renderer drives we; once render_done is high, pump takes over reads.
    // -------------------------------------------------------------------------
    reg [7:0] fb [0:FB_W * FB_H - 1];
    // initialise to 0 so partial renders look right
    integer init_i;
    initial for (init_i = 0; init_i < FB_W * FB_H; init_i = init_i + 1) fb[init_i] = 8'h00;

    reg         fb_we = 0;
    reg [12:0]  fb_waddr = 0;
    reg [7:0]   fb_wdata = 0;
    reg [12:0]  fb_raddr = 0;
    reg [7:0]   fb_rdata = 0;

    always @(posedge clk) begin
        if (fb_we) fb[fb_waddr] <= fb_wdata;
        fb_rdata <= fb[fb_raddr];
    end

    // -------------------------------------------------------------------------
    // Glyph atlas + per-glyph advance ROMs (loaded from .mem files).
    // -------------------------------------------------------------------------
    localparam integer CELL_SIZE = CELL_W * CELL_H;
    localparam integer ATLAS_SIZE = NUM_CHARS * CELL_SIZE;

    reg [7:0] atlas [0:ATLAS_SIZE - 1];
    initial $readmemh("glyph_atlas.mem", atlas);

    reg [7:0] advance_w [0:NUM_CHARS - 1];
    initial $readmemh("glyph_advance.mem", advance_w);

    // -------------------------------------------------------------------------
    // String ROM — what to render. Lines are zero-terminated (a zero byte means "end of line"; the renderer skips past padding). Edit and re-flash.
    // -------------------------------------------------------------------------
    reg [7:0] strings [0:STR_LEN - 1];
    integer si;
    initial begin
        for (si = 0; si < STR_LEN; si = si + 1) strings[si] = 8'h00;
        // line 0
        strings[ 0] = "P"; strings[ 1] = "I"; strings[ 2] = "P"; strings[ 3] = "E";
        // line 1
        strings[24] = "E"; strings[25] = "F"; strings[26] = "U"; strings[27] = "S";
        strings[28] = "E"; strings[29] = "D"; strings[30] = ":"; strings[31] = " ";
        strings[32] = "N"; strings[33] = "O";
        // line 2
        strings[48] = "R"; strings[49] = "E"; strings[50] = "Q"; strings[51] = ":";
        strings[52] = " "; strings[53] = "0"; strings[54] = "x"; strings[55] = "D";
        strings[56] = "E"; strings[57] = "A"; strings[58] = "D"; strings[59] = "B";
        strings[60] = "E"; strings[61] = "E"; strings[62] = "F";
        // line 3
        strings[72] = "O"; strings[73] = "U"; strings[74] = "T"; strings[75] = ":";
        strings[76] = " "; strings[77] = "0"; strings[78] = "x"; strings[79] = "1";
        strings[80] = "2"; strings[81] = "3"; strings[82] = "4"; strings[83] = "5";
        strings[84] = "6"; strings[85] = "7"; strings[86] = "8";
    end

    // Per-line baseline Y in framebuffer rows.
    function [6:0] line_baseline(input [1:0] ln);
        case (ln)
            2'd0: line_baseline = 7'd11;
            2'd1: line_baseline = 7'd27;
            2'd2: line_baseline = 7'd43;
            2'd3: line_baseline = 7'd59;
        endcase
    endfunction

    // -------------------------------------------------------------------------
    // Renderer FSM.
    // -------------------------------------------------------------------------
    localparam [3:0]
        R_BOOT     = 4'd0,  // wait a few cycles for $readmemh to settle
        R_LOAD     = 4'd1,  // fetch next char from strings[]
        R_LATCH    = 4'd2,  // wait one cycle so atlas/advance reads settle
        R_PX_READ  = 4'd3,  // read atlas pixel
        R_PX_WRITE = 4'd4,  // write framebuffer with max-blend
        R_ADV      = 4'd5,  // advance cursor, next char
        R_NEXT_LN  = 4'd6,
        R_DONE     = 4'd7;

    reg [3:0] rstate = R_BOOT;
    reg [4:0] boot_cnt = 0;

    reg [1:0]  line_idx     = 0;
    reg [4:0]  char_in_line = 0;
    reg [6:0]  cursor_x     = 0;
    reg [7:0]  char_ascii   = 0;
    reg [6:0]  glyph_idx    = 0;   // ascii - FIRST_CHAR
    reg [3:0]  px_i = 0;            // 0..CELL_W-1
    reg [3:0]  px_j = 0;            // 0..CELL_H-1

    wire signed [8:0] dst_x = $signed({2'b00, cursor_x}) - $signed({2'b00, PAD_LEFT[6:0]}) + $signed({5'b0, px_i});
    wire signed [8:0] dst_y = $signed({2'b00, line_baseline(line_idx)}) - $signed({2'b00, MAX_ASCENT[6:0]}) + $signed({5'b0, px_j});

    wire dst_in_range = (dst_x >= 0) && (dst_x < FB_W) && (dst_y >= 0) && (dst_y < FB_H);

    wire [14:0] atlas_addr = {glyph_idx, px_j[3:0], px_i[3:0]};
    reg  [7:0]  atlas_pix = 0;
    always @(posedge clk) atlas_pix <= atlas[atlas_addr];

    wire render_done = (rstate == R_DONE);

    always @(posedge clk) begin
        fb_we <= 1'b0;

        case (rstate)
            R_BOOT: begin
                boot_cnt <= boot_cnt + 1;
                if (&boot_cnt) begin
                    line_idx     <= 0;
                    char_in_line <= 0;
                    cursor_x     <= 0;
                    rstate       <= R_LOAD;
                end
            end

            R_LOAD: begin
                char_ascii <= strings[line_idx * MAX_CHARS_PER_LINE + char_in_line];
                rstate     <= R_LATCH;
            end

            R_LATCH: begin
                if (char_ascii == 8'h00) begin
                    rstate <= R_NEXT_LN;
                end else begin
                    glyph_idx <= char_ascii - FIRST_CHAR;
                    px_i      <= 0;
                    px_j      <= 0;
                    rstate    <= R_PX_READ;
                end
            end

            R_PX_READ: begin
                // atlas_pix updates one cycle after atlas_addr is set, so we wait through this state once per pixel for the read to settle.
                rstate <= R_PX_WRITE;
            end

            R_PX_WRITE: begin
                if (atlas_pix != 0 && dst_in_range) begin
                    fb_waddr <= dst_y[6:0] * FB_W + dst_x[7:0];
                    fb_wdata <= atlas_pix;
                    fb_we    <= 1'b1;
                end
                rstate <= R_ADV;
            end

            R_ADV: begin
                if (px_i == CELL_W - 1) begin
                    px_i <= 0;
                    if (px_j == CELL_H - 1) begin
                        // finished this glyph
                        cursor_x     <= cursor_x + advance_w[glyph_idx];
                        char_in_line <= char_in_line + 1;
                        if (char_in_line == MAX_CHARS_PER_LINE - 1) begin
                            rstate <= R_NEXT_LN;
                        end else begin
                            rstate <= R_LOAD;
                        end
                        px_j <= 0;
                    end else begin
                        px_j   <= px_j + 1;
                        rstate <= R_PX_READ;
                    end
                end else begin
                    px_i   <= px_i + 1;
                    rstate <= R_PX_READ;
                end
            end

            R_NEXT_LN: begin
                if (line_idx == NUM_LINES - 1) begin
                    rstate <= R_DONE;
                end else begin
                    line_idx     <= line_idx + 1;
                    char_in_line <= 0;
                    cursor_x     <= 0;
                    rstate       <= R_LOAD;
                end
            end

            R_DONE: begin
                // idle forever
            end
        endcase
    end

    // -------------------------------------------------------------------------
    // CE divider for the OLED pump.
    // -------------------------------------------------------------------------
    reg [$clog2(CLK_DIV)-1:0] cnt = 0;
    wire at_top = (cnt == CLK_DIV - 1);
    always @(posedge clk) cnt <= at_top ? 0 : cnt + 1;
    reg ce = 0;
    always @(posedge clk) ce <= at_top;

    // -------------------------------------------------------------------------
    // I2C driver.
    // -------------------------------------------------------------------------
    reg  [7:0] i2c_data;
    reg        i2c_start;
    reg        i2c_send_stop;
    wire       i2c_busy;

    ssd1306_i2c #(.CLK_DIV(CLK_DIV)) i2c (
        .clk(clk), .rst(1'b0),
        .data(i2c_data),
        .start(i2c_start),
        .send_start(1'b0),
        .send_stop(i2c_send_stop),
        .busy(i2c_busy),
        .scl(oled_scl), .sda(oled_sda)
    );

    // -------------------------------------------------------------------------
    // SSD1306 init sequence.
    // -------------------------------------------------------------------------
    localparam I2C_ADDR    = 8'h78;
    localparam CMD_PREFIX  = 8'h00;
    localparam DATA_PREFIX = 8'h40;
    localparam INIT_LEN    = 25;

    reg [7:0] init_cmds [0:INIT_LEN-1];
    initial begin
        init_cmds[ 0] = 8'hAE; init_cmds[ 1] = 8'hD5; init_cmds[ 2] = 8'h80;
        init_cmds[ 3] = 8'hA8; init_cmds[ 4] = 8'h3F; init_cmds[ 5] = 8'hD3;
        init_cmds[ 6] = 8'h00; init_cmds[ 7] = 8'h40; init_cmds[ 8] = 8'h8D;
        init_cmds[ 9] = 8'h14; init_cmds[10] = 8'hAD; init_cmds[11] = 8'h8B;
        init_cmds[12] = 8'hA1; init_cmds[13] = 8'hC8; init_cmds[14] = 8'hDA;
        init_cmds[15] = 8'h12; init_cmds[16] = 8'h81; init_cmds[17] = 8'hCF;
        init_cmds[18] = 8'hD9; init_cmds[19] = 8'hF1; init_cmds[20] = 8'hDB;
        init_cmds[21] = 8'h40; init_cmds[22] = 8'hA4; init_cmds[23] = 8'hA6;
        init_cmds[24] = 8'hAF;
    end

    // -------------------------------------------------------------------------
    // OLED pump FSM (unchanged from Phase 2A apart from using fb_raddr/fb_rdata).
    // -------------------------------------------------------------------------
    localparam [2:0]
        ST_RESET   = 3'd0, ST_SEND   = 3'd1, ST_WAIT  = 3'd2,
        ST_NEXT    = 3'd3, ST_BUSFREE = 3'd4, ST_GATHER = 3'd5;

    localparam [1:0]
        PH_INIT      = 2'd0, PH_PAGE_CMD = 2'd1, PH_PAGE_DATA = 2'd2;

    reg [2:0]  state       = ST_RESET;
    reg [1:0]  phase       = PH_INIT;
    reg [19:0] reset_cnt   = 0;
    reg [9:0]  busfree_cnt = 0;
    reg [4:0]  cmd_idx     = 0;
    reg [2:0]  page        = 0;
    reg [6:0]  col         = 0;
    reg [7:0]  px_byte     = 0;
    reg [3:0]  gather_cnt  = 0;

    always @(posedge clk) if (ce) begin
        fb_raddr  <= {page, gather_cnt[2:0], col};
        i2c_start <= 0;

        case (state)
            ST_RESET: begin
                reset_cnt <= reset_cnt + 1;
                // wait until renderer is finished AND reset counter elapsed
                if (&reset_cnt && render_done) begin
                    phase   <= PH_INIT;
                    cmd_idx <= 0;
                    page    <= 0;
                    col     <= 0;
                    state   <= ST_SEND;
                end
            end

            ST_SEND: begin
                if (!i2c_busy) begin
                    case (phase)
                        PH_INIT: begin
                            if (cmd_idx == 0)         begin i2c_data <= I2C_ADDR;             i2c_send_stop <= 0; end
                            else if (cmd_idx == 1)    begin i2c_data <= CMD_PREFIX;           i2c_send_stop <= 0; end
                            else                      begin i2c_data <= init_cmds[cmd_idx-2]; i2c_send_stop <= (cmd_idx == INIT_LEN + 1); end
                        end
                        PH_PAGE_CMD: begin
                            case (cmd_idx[2:0])
                                3'd0: begin i2c_data <= I2C_ADDR;             i2c_send_stop <= 0; end
                                3'd1: begin i2c_data <= CMD_PREFIX;           i2c_send_stop <= 0; end
                                3'd2: begin i2c_data <= 8'hB0 | {5'd0, page}; i2c_send_stop <= 0; end
                                3'd3: begin i2c_data <= 8'h02;                i2c_send_stop <= 0; end
                                3'd4: begin i2c_data <= 8'h10;                i2c_send_stop <= 1; end
                                default: ;
                            endcase
                        end
                        PH_PAGE_DATA: begin
                            if (cmd_idx == 0)         begin i2c_data <= I2C_ADDR;    i2c_send_stop <= 0; end
                            else if (cmd_idx == 1)    begin i2c_data <= DATA_PREFIX; i2c_send_stop <= 0; end
                            else                      begin i2c_data <= px_byte;     i2c_send_stop <= (col == 7'd127); end
                        end
                    endcase
                    i2c_start <= 1;
                    state     <= ST_WAIT;
                end
            end

            ST_WAIT: begin
                if (i2c_busy) state <= ST_NEXT;
            end

            ST_NEXT: begin
                if (!i2c_busy) begin
                    case (phase)
                        PH_INIT: begin
                            if (cmd_idx == INIT_LEN + 1) begin
                                phase   <= PH_PAGE_CMD;
                                cmd_idx <= 0;
                                page    <= 0;
                                state   <= ST_BUSFREE;
                            end else begin
                                cmd_idx <= cmd_idx + 1;
                                state   <= ST_SEND;
                            end
                        end
                        PH_PAGE_CMD: begin
                            if (cmd_idx == 4) begin
                                phase      <= PH_PAGE_DATA;
                                cmd_idx    <= 0;
                                col        <= 0;
                                gather_cnt <= 0;
                                state      <= ST_BUSFREE;
                            end else begin
                                cmd_idx <= cmd_idx + 1;
                                state   <= ST_SEND;
                            end
                        end
                        PH_PAGE_DATA: begin
                            if (cmd_idx < 2) begin
                                cmd_idx <= cmd_idx + 1;
                                if (cmd_idx == 1) begin
                                    gather_cnt <= 0;
                                    state      <= ST_GATHER;
                                end else begin
                                    state <= ST_SEND;
                                end
                            end else if (col == 7'd127) begin
                                phase   <= PH_PAGE_CMD;
                                cmd_idx <= 0;
                                page    <= (page == 3'd7) ? 3'd0 : page + 1;
                                state   <= ST_BUSFREE;
                            end else begin
                                col        <= col + 1;
                                gather_cnt <= 0;
                                state      <= ST_GATHER;
                            end
                        end
                    endcase
                end
            end

            ST_BUSFREE: begin
                busfree_cnt <= busfree_cnt + 1;
                if (&busfree_cnt) begin
                    busfree_cnt <= 0;
                    state       <= ST_SEND;
                end
            end

            ST_GATHER: begin
                gather_cnt <= gather_cnt + 1;
                if (gather_cnt >= 4'd1) begin
                    px_byte <= {(fb_rdata >= trng_out), px_byte[7:1]};
                end
                if (gather_cnt == 4'd8) begin
                    gather_cnt <= 0;
                    state      <= ST_SEND;
                end
            end
        endcase
    end

endmodule
