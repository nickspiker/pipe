//! Generate test vectors for the Verilog testbenches.
//!
//! Emits hex lines suitable for $readmemh in tb_chaos_amp.v and tb_pipe_mac.v.
//! Each vector: 64-byte input → 32-byte key → expected chaos state, expected MAC.

use pipe::{chaos_amp, pipe_mac};
use pipe::chaos_amp::state_to_bytes;

fn main() {
    println!("// PIPE chaos_amp + MAC test vectors");
    println!("// Generated by pipe::gen_test_vectors. Do not edit by hand.");
    println!("// Format per vector (4 hex lines):");
    println!("//   input         (64 bytes)");
    println!("//   chaos_state   (64 bytes — 16 × LE u32)");
    println!("//   key           (32 bytes)");
    println!("//   mac           (32 bytes)");
    println!();

    print_vector(&[0u8; 64], &[0; 32]);
    print_vector(&[0xFFu8; 64], &[0xFF; 32]);

    let mut inp = [0u8; 64];
    for i in 0..64 { inp[i] = i as u8; }
    let mut key = [0u8; 32];
    for i in 0..32 { key[i] = (i * 7) as u8; }
    print_vector(&inp, &key);

    let h = blake3::hash(b"PIPE-test-3");
    let hb = h.as_bytes();
    let mut inp3 = [0u8; 64];
    inp3[..32].copy_from_slice(hb);
    inp3[32..].copy_from_slice(hb);
    print_vector(&inp3, hb);
}

fn print_vector(input: &[u8; 64], key: &[u8; 32]) {
    let state = chaos_amp(input);
    let state_bytes = state_to_bytes(&state);
    let mac = pipe_mac(key, input);

    print!("// input:        ");
    for b in input.iter() { print!("{:02x}", b); }
    println!();
    print!("// chaos_state:  ");
    for b in state_bytes.iter() { print!("{:02x}", b); }
    println!();
    print!("// key:          ");
    for b in key.iter() { print!("{:02x}", b); }
    println!();
    print!("// mac:          ");
    for b in mac.iter() { print!("{:02x}", b); }
    println!();
    println!();
}
