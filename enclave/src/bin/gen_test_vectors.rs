//! Generate test vectors for the Verilog testbenches.
//!
//! Two outputs in one run:
//!
//! 1. **Human-readable comments** to stdout — input/state/key/mac per vector.
//! 2. **$readmemh-friendly files** to a directory passed as argv[1]: each vector contributes 16 lines (one u32 per bucket, hex) to `vectors_input.mem` and another 16 lines to `vectors_state.mem`. Buckets are little-endian (bytes [4i..4i+4] form bucket i, matching `chaos_amp::state_to_bytes`). The Verilog testbench reads these via `$readmemh` into `reg [31:0]` arrays.
//!
//! If argv[1] is omitted, only stdout output happens. Typical use:
//!
//! ```text
//! cargo run --release --bin gen-test-vectors -- ../sim
//! ```

use pipe::{chaos_amp, pipe_mac};
use pipe::chaos_amp::state_to_bytes;

fn main() {
    let mem_dir = std::env::args().nth(1);

    println!("// PIPE chaos_amp + MAC test vectors");
    println!("// Generated by pipe::gen_test_vectors. Do not edit by hand.");
    println!("// Format per vector (4 hex lines):");
    println!("//   input         (64 bytes)");
    println!("//   chaos_state   (64 bytes — 16 × LE u32)");
    println!("//   key           (32 bytes)");
    println!("//   mac           (32 bytes)");
    println!();

    let mut vectors: Vec<([u8; 64], [u8; 32])> = Vec::new();

    vectors.push(([0u8; 64], [0; 32]));
    vectors.push(([0xFFu8; 64], [0xFF; 32]));

    let mut inp = [0u8; 64];
    for i in 0..64 { inp[i] = i as u8; }
    let mut key = [0u8; 32];
    for i in 0..32 { key[i] = (i * 7) as u8; }
    vectors.push((inp, key));

    let h = blake3::hash(b"PIPE-test-3");
    let hb = h.as_bytes();
    let mut inp3 = [0u8; 64];
    inp3[..32].copy_from_slice(hb);
    inp3[32..].copy_from_slice(hb);
    vectors.push((inp3, *hb));

    let mut input_mem = String::new();
    let mut state_mem = String::new();

    for (input, key) in &vectors {
        let state = chaos_amp(input);
        let state_bytes = state_to_bytes(&state);
        let mac = pipe_mac(key, input);

        print_vector_comment(input, &state_bytes, key, &mac);

        for chunk in input.chunks(4) {
            let v = u32::from_le_bytes([chunk[0], chunk[1], chunk[2], chunk[3]]);
            input_mem.push_str(&format!("{:08x}\n", v));
        }
        for &word in &state {
            state_mem.push_str(&format!("{:08x}\n", word));
        }
    }

    if let Some(dir) = mem_dir {
        let p_in = format!("{}/vectors_input.mem", dir);
        let p_st = format!("{}/vectors_state.mem", dir);
        std::fs::write(&p_in, &input_mem).expect("write vectors_input.mem");
        std::fs::write(&p_st, &state_mem).expect("write vectors_state.mem");
        eprintln!("wrote {} ({} vectors)", p_in, vectors.len());
        eprintln!("wrote {} ({} vectors)", p_st, vectors.len());
    }
}

fn print_vector_comment(
    input: &[u8; 64],
    state_bytes: &[u8; 64],
    key: &[u8; 32],
    mac: &[u8; 32],
) {
    print!("// input:        ");
    for b in input.iter() { print!("{:02x}", b); }
    println!();
    print!("// chaos_state:  ");
    for b in state_bytes.iter() { print!("{:02x}", b); }
    println!();
    print!("// key:          ");
    for b in key.iter() { print!("{:02x}", b); }
    println!();
    print!("// mac:          ");
    for b in mac.iter() { print!("{:02x}", b); }
    println!();
    println!();
}
