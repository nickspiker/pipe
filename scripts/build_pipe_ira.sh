#!/usr/bin/env bash
# =============================================================================
# build_pipe_ira.sh — first-silicon ira ceremony bitstream
# =============================================================================
# Builds top_pipe_ira.v: 8 rings + trng + blake3_tree + otp + verify + ira_fsm.
# Press Enter (dozenal keypad p51+p56 = R13) → VIRGIN → KOHI → BLAKE3 → TAHU →
# HEALTHY. T6 LED indicates progress; T2 = FUCKED.
# =============================================================================
set -e

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="$SCRIPT_DIR/.."
RTL="$ROOT/rtl"
MEASURE="$ROOT/rtl/measure"
LPF="$ROOT/constraints/pipe_ira.lpf"
BUILD="$ROOT/build_pipe_ira"
SEED="${SEED:-4}"

PROGRAM=0
FLASH=0
for arg in "$@"; do
    case "$arg" in
        --program) PROGRAM=1 ;;
        --flash)   FLASH=1   ;;
    esac
done

mkdir -p "$BUILD"

# Glyph atlas mem files for the OLED text renderer. Generated by
# tools/oled-bake-atlas; we just copy the pre-baked outputs alongside the
# build so $readmemh can find them at synth time (yosys reads them relative
# to its current working directory).
cp "$ROOT/rtl/glyph_atlas.mem"    "$BUILD/"
cp "$ROOT/rtl/glyph_advance.mem"  "$BUILD/"

echo "================================================================"
echo " First-silicon ira ceremony + OLED hex display"
echo "================================================================"

echo ""
echo "--- Synthesise ---"
(cd "$BUILD" && yosys -p "
    read_verilog -I $RTL $RTL/blake3/blake3.v
    read_verilog -I $RTL $RTL/blake3_tree.v
    read_verilog -I $RTL $RTL/trng.v
    read_verilog -I $RTL $RTL/otp.v
    read_verilog -I $RTL $RTL/inverted_pair_verify.v
    read_verilog -I $RTL $RTL/ira_fsm.v
    read_verilog -I $RTL $RTL/ssd1306_i2c.v
    read_verilog -I $RTL $RTL/oled_greyscale_driver.v
    read_verilog -I $RTL $RTL/oled_text_renderer.v
    read_verilog -I $RTL $MEASURE/top_pipe_ira.v
    synth_ecp5 -nowidelut -abc2 -top top_pipe_ira -json pipe_ira.json
    stat
") > "$BUILD/yosys.log" 2>&1

if grep -q 'ERROR' "$BUILD/yosys.log"; then
    echo "YOSYS ERROR — see $BUILD/yosys.log"
    tail -30 "$BUILD/yosys.log"
    exit 1
fi
grep -E '^\s+[0-9]+ +(LUT4|TRELLIS_FF|CCU2C|DP16KD)' "$BUILD/yosys.log" | tail -10

echo ""
echo "--- Place & Route ---"
nextpnr-ecp5 --25k --package CABGA256 --speed 6 --seed "$SEED" \
    --lpf "$LPF" \
    --json "$BUILD/pipe_ira.json" \
    --textcfg "$BUILD/pipe_ira.config" \
    --ignore-loops --timing-allow-fail \
    > "$BUILD/pnr.log" 2>&1

if grep -q 'ERROR' "$BUILD/pnr.log"; then
    echo "PNR ERROR — see $BUILD/pnr.log"
    tail -30 "$BUILD/pnr.log"
    exit 1
fi
grep -E "(Max frequency|Total LUT4|Info: Device utilisation)" "$BUILD/pnr.log" | head -6

echo ""
echo "--- Pack bitstream ---"
ecppack --svf "$BUILD/pipe_ira.svf" "$BUILD/pipe_ira.config" "$BUILD/pipe_ira.bit"
echo "Bitstream: $BUILD/pipe_ira.bit ($(stat -c%s "$BUILD/pipe_ira.bit") bytes)"

if [ "$PROGRAM" -eq 1 ]; then
    echo ""
    echo "--- Program SRAM ---"
    openFPGALoader -c ft232 "$BUILD/pipe_ira.svf"
fi

if [ "$FLASH" -eq 1 ]; then
    echo ""
    echo "--- Write flash ---"
    openFPGALoader -c ft232 --write-flash "$BUILD/pipe_ira.bit"
fi

echo ""
echo "Done."
echo ""
echo "Usage:"
echo "  Power on:  T6 LED OFF (VIRGIN, idle, awaiting provision request)"
echo "  Press Enter on dozenal keypad (p51+p56 via R13):"
echo "    T6 fast-blinks for ~150 ms (KOHI gather)"
echo "    T6 still blinking ~25 ms more (BLAKE3 hashing)"
echo "    T6 blinks briefly ~1 µs (8 OTP burns)"
echo "    T6 goes solid ON when HEALTHY"
echo "  If T2 lights solid: chip is FUCKED (rings unhealthy or burn fault)"
echo "  Power-cycle to return to VIRGIN (FPGA emulation does not persist OTP)"
